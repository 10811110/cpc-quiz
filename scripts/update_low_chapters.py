# 處理指定章節
chapters_to_update = [
    (5, chapter5_explanations, "第五章 風險評估"),
    (7, chapter7_explanations, "第七章 採購及變更管理"),
    (8, chapter8_explanations, "第八章 緊急應變管理"),
    (11, chapter11_explanations, "第十一章 火災爆炸危害預防"),
]

print("=" * 80)
print("📝 補充低完整度章節詳解")
print("=" * 80)

for ch_num, explanations, ch_name in chapters_to_update:
    ch_file = f'{quiz_dir}chapter{ch_num}.json'
    if not os.path.exists(ch_file):
        print(f"\n⚠️  第{ch_num}章檔案不存在")
        continue
    
    print(f"\n處理 {ch_name}...")
    
    with open(ch_file, 'r', encoding='utf-8') as f:
        ch = json.load(f)
    
    updated = 0
    for q in ch['questions']:
        qid = q['id']
        old_analysis = q.get('analysis', '')
        
        # 如果已經是完整詳解（長度>80 且不含制式文字），跳過
        if len(old_analysis) > 80 and '本題正確答案為' not in old_analysis:
            continue
        
        # 查找匹配的詳解
        if qid in explanations:
            analysis, law, tip = explanations[qid]
            q['analysis'] = analysis
            q['law'] = law
            q['tip'] = tip
            updated += 1
        else:
            # 沒有特定詳解的題目，使用通用但較完整的說明
            answer = q['answer']
            question = q['question']
            q['analysis'] = f"本題正確答案為{answer}。此為{ch_name}的重要概念，涉及職業安全衛生的專業知識。建議熟記相關法規與標準，理解其背後的安全原理與實踐方法。"
            q['law'] = ch_name
            q['tip'] = f"掌握{ch_name.split(' ')[-1]}關鍵字，理解安全原理，多練習類似題型"
            updated += 1
    
    # 保存
    tmp = ch_file + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(ch, f, ensure_ascii=False, indent=2)
    os.replace(tmp, ch_file)
    
    # 統計
    detailed = sum(1 for q in ch['questions'] if len(q.get('analysis', '')) > 80 and '本題正確答案' not in q.get('analysis', ''))
    total = len(ch['questions'])
    print(f"   ✅ 更新{updated}題 | 完整詳解：{detailed}/{total} ({detailed/total*100:.1f}%)")

print("\n" + "=" * 80)
print("✅ 低完整度章節詳解補充完成！")
print("=" * 80)
