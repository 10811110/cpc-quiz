import json

import os
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
quiz_dir = PROJECT_ROOT

def update_chapter(ch_num, explanations_dict):
    """更新章節詳解"""
    ch_file = f'{quiz_dir}chapter{ch_num}.json'
    with open(ch_file, 'r', encoding='utf-8') as f:
        ch = json.load(f)
    
    updated = 0
    for q in ch['questions']:
        qid = q['id']
        if qid in explanations_dict:
            analysis, law, tip = explanations_dict[qid]
            q['analysis'] = analysis
            q['law'] = law
            q['tip'] = tip
            updated += 1
    
    tmp = ch_file + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(ch, f, ensure_ascii=False, indent=2)
    os.replace(tmp, ch_file)
    
    # 統計
    detailed = sum(1 for q in ch['questions'] if len(q.get('analysis', '')) > 80 and '本題正確答案' not in q.get('analysis', ''))
    total = len(ch['questions'])
    return updated, detailed, total

